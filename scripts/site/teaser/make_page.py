"""Write the Fig. 1 capture page from the site's own 3D legal network page, so the two never drift apart.

    python scripts/site/teaser/make_page.py          # writes teaser.html and teaser_data.js next to this script
    python scripts/site/teaser/make_page.py --check  # exit 1 if the committed files differ from what it would write

teaser.html = site/network-3d.html with a <base href="../../../site/"> (scripts, styles and the network's lazily loaded
data resolve inside site/, over http and file://), noindex, the capture stylesheet (teaser.css) and, after
js/network3d.js, teaser_data.js (teaser_config.json + trace_138008514.json as a classic script, no fetch),
teaser-core.js and teaser.js. The page is not part of the published site (it lives under scripts/).
"""
import json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, "..", "..", ".."))
SRC = os.path.join(REPO, "site", "network-3d.html")
REL = "../scripts/site/teaser/"                       # from site/ (the base) back to this folder


def build():
    html = open(SRC, encoding="utf-8").read()
    head = "<head>\n"
    if html.count(head) != 1 or html.count('<script src="js/network3d.js"></script>') != 1:
        sys.exit("site/network-3d.html changed shape: update make_page.py")
    html = html.replace(head, head + '<base href="../../../site/">\n<meta name="robots" content="noindex">\n', 1)
    links = [l for l in html.split("\n") if l.startswith('<link rel="stylesheet"')]
    html = html.replace(links[-1], links[-1] + '\n<link rel="stylesheet" href="%steaser.css">' % REL, 1)
    t0, t1 = html.index("<title>"), html.index("</title>")
    html = html[:t0] + "<title>Fig. 1 capture of the 3D legal network · VLOnto (scripts/site/teaser, not part of the site)" + html[t1:]
    tail = "".join('\n<script src="%s%s"></script>' % (REL, f) for f in ("teaser_data.js", "teaser-core.js", "teaser.js"))
    html = html.replace('<script src="js/network3d.js"></script>', '<script src="js/network3d.js"></script>' + tail, 1)
    cfg = json.load(open(os.path.join(HERE, "teaser_config.json"), encoding="utf-8"))
    tr = json.load(open(os.path.join(HERE, "trace_138008514.json"), encoding="utf-8"))
    data = ("/* generated by make_page.py from teaser_config.json and trace_138008514.json; do not edit */\n"
            "window.VLONTO_TEASER = " + json.dumps({"config": cfg, "trace": tr}, ensure_ascii=False, separators=(",", ":")) + ";\n")
    return {"teaser.html": html, "teaser_data.js": data}


def main():
    out = build()
    if "--check" in sys.argv:
        bad = [n for n, s in out.items() if not os.path.exists(os.path.join(HERE, n)) or
               open(os.path.join(HERE, n), encoding="utf-8").read() != s]
        if bad:
            sys.exit("out of date (run scripts/site/teaser/make_page.py): " + ", ".join(bad))
        print("teaser.html and teaser_data.js are up to date")
        return
    for n, s in out.items():
        with open(os.path.join(HERE, n), "w", encoding="utf-8", newline="\n") as f:
            f.write(s)
        print("wrote", os.path.relpath(os.path.join(HERE, n), REPO), len(s.encode("utf-8")), "bytes")


if __name__ == "__main__":
    main()

#!/usr/bin/env bash
# chrome.sh - the pinned chrome-headless-shell (Chrome for Testing, see versions.lock) configured for VLOnto:
#   * LD_LIBRARY_PATH = ROOT/tools/chrome/lib only: the 8 conda-forge libraries the node lacks
#     (system glib, dbus, fontconfig, libstdc++ are still used)
#   * FONTCONFIG_FILE = generated config that exposes ONLY the vendored fonts in <repo>/typst/fonts
#     (Be Vietnam Pro, Noto Serif, JetBrains Mono NL, Noto Sans Symbols 2, Noto Sans Math). A character no
#     vendored font has renders as a tofu box instead of being silently covered by some system font.
#   * WebGL on CPU: --use-angle=swiftshader --enable-unsafe-swiftshader (ANGLE -> SwiftShader Vulkan)
#   * --no-sandbox (Ubuntu 26.04 restricts unprivileged user namespaces); VLONTO_CHROME_SANDBOX=1 keeps it.
# It never adds --allow-file-access-from-files: file:// pages run with default browser rules.
#
# CLI:         tools/chrome.sh --screenshot=out.png --window-size=1440,900 --virtual-time-budget=8000 file:///abs/page.html
#              tools/chrome.sh --dump-dom file:///abs/page.html
#              tools/chrome.sh --version
# Playwright:  p.chromium.launch(executable_path="<repo>/tools/chrome.sh")   (what site_check.py does)
# Env:         VLONTO_ROOT (default: parent of the repo dir), VLONTO_FONT_DIRS (colon list, default <repo>/typst/fonts)
set -euo pipefail
HERE=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
REPO=$(dirname "$HERE")
# shellcheck disable=SC1091
source "$HERE/versions.lock"
ROOT=${VLONTO_ROOT:-$(dirname "$REPO")}
BIN=$ROOT/tools/chrome/$CHROME_VERSION/chrome-headless-shell-linux64/chrome-headless-shell
LIB=$ROOT/tools/chrome/lib
if [ ! -x "$BIN" ]; then echo "chrome.sh: $BIN not found - run tools/setup_tools.sh" >&2; exit 127; fi
FC=${VLONTO_FONTCONFIG_DIR:-$ROOT/build/fontconfig}
mkdir -p "$FC/cache"
DIRS=""
IFS=: read -r -a _fd <<< "${VLONTO_FONT_DIRS:-$REPO/typst/fonts}"
for d in "${_fd[@]}"; do DIRS="$DIRS  <dir>$d</dir>"$'\n'; done
CONF="<?xml version=\"1.0\"?>
<!DOCTYPE fontconfig SYSTEM \"urn:fontconfig:fonts.dtd\">
<!-- generated by tools/chrome.sh: vendored fonts only -->
<fontconfig>
$DIRS  <cachedir>$FC/cache</cachedir>
  <alias binding=\"same\"><family>sans-serif</family><prefer><family>Be Vietnam Pro</family><family>Noto Sans Symbols 2</family><family>Noto Sans Math</family></prefer></alias>
  <alias binding=\"same\"><family>serif</family><prefer><family>Noto Serif</family><family>Noto Sans Symbols 2</family><family>Noto Sans Math</family></prefer></alias>
  <alias binding=\"same\"><family>monospace</family><prefer><family>JetBrains Mono NL</family><family>Noto Sans Symbols 2</family><family>Noto Sans Math</family></prefer></alias>
</fontconfig>"
if [ ! -f "$FC/fonts.conf" ] || [ "$(cat "$FC/fonts.conf")" != "$CONF" ]; then
  printf '%s\n' "$CONF" > "$FC/fonts.conf.$$" && mv -f "$FC/fonts.conf.$$" "$FC/fonts.conf"
fi
export FONTCONFIG_FILE=$FC/fonts.conf
export LD_LIBRARY_PATH=$LIB${LD_LIBRARY_PATH:+:$LD_LIBRARY_PATH}
FLAGS=(--use-angle=swiftshader --enable-unsafe-swiftshader --ignore-gpu-blocklist --hide-scrollbars)
[ "${VLONTO_CHROME_SANDBOX:-0}" = 1 ] || FLAGS+=(--no-sandbox)
exec "$BIN" "${FLAGS[@]}" "$@"
